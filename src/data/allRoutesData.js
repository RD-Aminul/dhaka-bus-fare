export const BRTA_RATE_PER_KM = 2.70;
export const BRTA_MIN_FARE = 10.0;

// Helper to calculate exact BRTA chart fare between two cumulative km points
export function calculatePdfFare(kmA, kmB) {
  const dist = Math.abs(Number((kmB - kmA).toFixed(1)));
  if (dist === 0) return 0;
  
  // Specific PDF chart rounding edge-cases observed in official BRTA document
  if (dist <= 3.7) return 10;
  if (dist >= 3.8 && dist <= 4.0) return 10; // e.g. 3.9 km in A-101 is 10.00 tk

  const rawFare = dist * BRTA_RATE_PER_KM;
  return Math.max(BRTA_MIN_FARE, Math.round(rawFare));
}

