// Helper to get English name for any stop
export function getStopEnglishName(stopName) {
  if (!stopName) return '';
  const cleanName = stopName.trim();
  if (STOP_ENGLISH_MAP[cleanName]) {
    return STOP_ENGLISH_MAP[cleanName];
  }
  
  // Try partial key match
  for (const [bnKey, enVal] of Object.entries(STOP_ENGLISH_MAP)) {
    if (cleanName.includes(bnKey) || bnKey.includes(cleanName)) {
      return enVal;
    }
  }

  return cleanName;
}
