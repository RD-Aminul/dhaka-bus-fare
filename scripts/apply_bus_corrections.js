let filePath = 'src/data/allRoutesData.js';
let content = fs.readFileSync(filePath, 'utf8');

let updatedCount = 0;
for (const [routeId, buses] of Object.entries(REAL_BUS_CORRECTIONS)) {
  // Regex to find route block by id and replace its buses array
  // Pattern: ("id":\s*"routeId"[^}]*?"buses":\s*\[)([^\]]*?)(\])
  const escapedId = routeId.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const regex = new RegExp(`("id":\\s*"${escapedId}"[\\s\\S]*?"buses":\\s*\\[)[\\s\\S]*?(\\])`, 'g');
  
  if (regex.test(content)) {
    const formattedBuses = buses.map(b => `\n      "${b}"`).join(',') + '\n    ';
    content = content.replace(regex, `$1${formattedBuses}$2`);
    updatedCount++;
  } else {
    console.warn(`Route ID ${routeId} not matched in content!`);
  }
}

fs.writeFileSync(filePath, content, 'utf8');
console.log(`Successfully updated real-world bus mappings for ${updatedCount} routes in allRoutesData.js!`);
